'use strict';

const fs = require('fs-extra');
const path = require('path');
const { logInfo, logSuccess } = require('./logger');
const { installDevDependency } = require('./packageManager');
const { execSync } = require('child_process');

const os = require('os');

const SONAR_PROPS_FILE = 'sonar-project.properties';

// Per-developer SonarQube dashboard login, saved when the broker creates the
// account and printed by the pre-commit hook (lib/hooks.js reads this file).
const DASHBOARD_CREDS_FILE = path.join(os.homedir(), '.cs-devtest', 'sonar-dashboard.env');

// Non-secret broker URL: the on-prem server's static LAN IP, so developers
// need no DNS or /etc/hosts setup. If the server ever moves, update this and
// publish a new version; until then any machine can override it with the
// CS_DEVTEST_BROKER_URL env var.
const DEFAULT_BROKER_URL = 'http://192.168.2.50:8900';

// ─────────────────────────────────────────────────────────────
// HELPER FUNCTIONS
// ─────────────────────────────────────────────────────────────
function getGitEmail() {
  try {
    return execSync('git config user.email').toString().trim();
  } catch {
    return null;
  }
}

// §3.0 canonical project-key transform — kept in sync with the broker, which
// re-applies it server-side authoritatively.
function normalizeProjectKey(name) {
  return String(name).toLowerCase().replace(/[^a-z0-9._:-]/g, '-');
}

async function ensureGitignored(entry) {
  try {
    const gitignorePath = path.join(process.cwd(), '.gitignore');
    let contents = '';
    if (await fs.pathExists(gitignorePath)) {
      contents = await fs.readFile(gitignorePath, 'utf8');
    }
    const already = contents
      .split(/\r?\n/)
      .some((line) => line.trim() === entry);
    if (!already) {
      const prefix = contents && !contents.endsWith('\n') ? '\n' : '';
      await fs.appendFile(gitignorePath, `${prefix}${entry}\n`);
    }
  } catch {
    /* non-fatal — .gitignore maintenance is best-effort */
  }
}

async function saveDashboardCreds({ url, login, password }) {
  try {
    await fs.ensureDir(path.dirname(DASHBOARD_CREDS_FILE), { mode: 0o700 });
    await fs.writeFile(
      DASHBOARD_CREDS_FILE,
      `SONAR_DASHBOARD_URL=${url}\nSONAR_DASHBOARD_LOGIN=${login}\nSONAR_DASHBOARD_PASSWORD=${password}\n`,
      { mode: 0o600 }
    );
    await fs.chmod(DASHBOARD_CREDS_FILE, 0o600);
  } catch (err) {
    logInfo(`WARNING: could not save SonarQube login to ${DASHBOARD_CREDS_FILE} (${err.message}).`);
  }
}

async function readDashboardCreds() {
  try {
    const text = await fs.readFile(DASHBOARD_CREDS_FILE, 'utf8');
    const get = (key) => {
      const line = text.split(/\r?\n/).find((l) => l.startsWith(`${key}=`));
      return line ? line.slice(key.length + 1) : '';
    };
    return {
      url: get('SONAR_DASHBOARD_URL'),
      login: get('SONAR_DASHBOARD_LOGIN'),
      password: get('SONAR_DASHBOARD_PASSWORD'),
    };
  } catch {
    return null;
  }
}

async function writeSonarProps(propsPath, { hostUrl, token, projectKey, projectName }) {
  // NOTE: the key is `sonar.login=` (not `sonar.token=`). The pre-commit hook's
  // skip-guard in lib/hooks.js greps `^sonar.login=` (placeholder/empty) to
  // decide whether to skip the scan, so writer and guard must agree on this key.
  await fs.writeFile(
    propsPath,
    `# Auto-generated by cs-devtest
sonar.host.url=${hostUrl}
sonar.login=${token}
sonar.projectKey=${projectKey}
sonar.projectName=${projectName}
sonar.sources=.
sonar.javascript.node.maxspace=4096
sonar.exclusions=**/node_modules/**,**/dist/**,**/build/**,**/.next/**,**/coverage/**,**/.venv/**
`
  );
}

// ─────────────────────────────────────────────────────────────
// INSTALL SCANNER
// ─────────────────────────────────────────────────────────────
exports.installSonarScanner = async () => {
  logInfo('Installing sonarqube-scanner...');
  await installDevDependency('sonarqube-scanner');
  logSuccess('sonarqube-scanner installed.');
};

// ─────────────────────────────────────────────────────────────
// MAIN SETUP FUNCTION
// ─────────────────────────────────────────────────────────────
// Calls the on-prem credential broker to provision the SonarQube project and
// mint a project-scoped scanner token. No admin token, password, or server IP
// is baked into this package. Never throws — on any failure it degrades to an
// empty token so the pre-commit hook skips the scan instead of blocking commits.
exports.setupSonarProperties = async () => {
  const propsPath = path.join(process.cwd(), SONAR_PROPS_FILE);

  let projectKey = 'my-project';
  let projectName = 'My Project';

  const pkgPath = path.join(process.cwd(), 'package.json');
  if (await fs.pathExists(pkgPath)) {
    const pkg = await fs.readJSON(pkgPath);
    if (pkg.name) {
      projectKey = normalizeProjectKey(pkg.name);
      projectName = pkg.name;
    }
  }

  // Keep the generated file out of version control (the scoped token is
  // disposable but must not be committed).
  await ensureGitignored(SONAR_PROPS_FILE);

  const brokerUrl = (process.env.CS_DEVTEST_BROKER_URL || DEFAULT_BROKER_URL).replace(/\/+$/, '');
  const gitEmail = getGitEmail();

  if (typeof fetch !== 'function') {
    logInfo(
      'WARNING: global fetch unavailable (Node < 18) — cannot reach the broker. Writing sonar-project.properties without a token; SonarQube scan will be skipped.'
    );
    await writeSonarProps(propsPath, { hostUrl: '', token: '', projectKey, projectName });
    logSuccess(`Created ${propsPath}`);
    return;
  }

  try {
    const res = await fetch(`${brokerUrl}/sonar/provision`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ projectKey, projectName, gitEmail }),
      signal: AbortSignal.timeout(15000),
    });

    if (!res.ok) {
      logInfo(
        `WARNING: broker /sonar/provision returned HTTP ${res.status}. Writing sonar-project.properties without a token; SonarQube scan will be skipped.`
      );
      await writeSonarProps(propsPath, { hostUrl: '', token: '', projectKey, projectName });
      logSuccess(`Created ${propsPath}`);
      return;
    }

    const data = await res.json();
    await writeSonarProps(propsPath, {
      hostUrl: data.hostUrl || '',
      token: data.scannerToken || '',
      projectKey: data.projectKey || projectKey,
      projectName,
    });
    logSuccess(`Created ${propsPath}`);

    if (data.dashboardLogin && data.dashboardPassword) {
      await saveDashboardCreds({
        url: data.hostUrl || '',
        login: data.dashboardLogin,
        password: data.dashboardPassword,
      });
    }
    const creds = await readDashboardCreds();
    if (data.dashboardUrl) {
      console.log('\n SonarQube Login');
      console.log(`URL:      ${data.dashboardUrl}`);
      if (data.dashboardLogin) {
        console.log(`Username: ${data.dashboardLogin}`);
        if (creds && creds.login === data.dashboardLogin && creds.password) {
          console.log(`Password: ${creds.password}`);
          console.log(`(saved in ${DASHBOARD_CREDS_FILE})\n`);
        } else {
          console.log('Password: account already existed and no password is saved on this machine —');
          console.log('          ask your SonarQube admin to reset it.\n');
        }
      } else {
        logInfo('No git email found — skipping user setup. Run: git config user.email "your@email.com"');
      }
    }
  } catch (err) {
    logInfo(
      `WARNING: could not reach the credential broker at ${brokerUrl} (${err.message}). ` +
        'Writing sonar-project.properties without a token; SonarQube scan will be skipped. ' +
        'Check that you are on the office network, or set CS_DEVTEST_BROKER_URL to the on-prem broker.'
    );
    await writeSonarProps(propsPath, { hostUrl: '', token: '', projectKey, projectName });
    logSuccess(`Created ${propsPath}`);
  }
};

// Re-exported for tooling/tests.
exports.getGitEmail = getGitEmail;
exports.normalizeProjectKey = normalizeProjectKey;
